export function lookupSell<T>(table: Record<string, T>, path: string): T | null {
  const p = norm(path);
  if (table[p]) return table[p];
  for (const [key, value] of Object.entries(table)) {
    if (norm(key) === p) return value;
  }
  return null;
}

export function teachersForCourse(path: string, teachers: TeacherCard[]) {
  const keys = lookupSell(COURSE_TEACHERS, path);
  if (!keys?.length) return [];
  return teachers
    .filter((t) => t.href !== "/team" && keys.some((key) => t.name.includes(key)))
    .slice(0, 3);
}