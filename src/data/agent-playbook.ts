export function playbookPrompt(scripts: ScriptSection[], facts?: SessionFacts, now = new Date()) {
  const season = summerSeason(now)
    ? "Сейчас сезон лета (апрель–август): летние программы можно предлагать после направления."
    : "Сейчас не сезон лета: летние программы, лагерь и летний клуб не предлагай, пока родитель сам не спросит.";
  const closed: string[] = [];
  if (facts?.age) closed.push("возраст");
  if (facts?.city) closed.push("город");
  if (facts?.branchId) closed.push("филиал");
  if (facts?.school) closed.push("направление");
  const skip = new Set<ScriptStep>();
  if (facts?.age) skip.add("age");
  if (facts?.city) skip.add("city");
  if (facts?.branchId) skip.add("branch");
  const live = [
    "Воронка: один новый вопрос. Закрытые шаги не повторяй даже другими словами.",
    facts ? `Сейчас: ${nextStepOf(facts)}` : "Воронка на кнопках. Возраст и город не спрашивай.",
    closed.length ? `Уже есть, ЗАПРЕЩЕНО спрашивать: ${closed.join(", ")}.` : "",
    facts?.city ? `Город уже ${facts.city}. Фразы «Коломна или Луховицы», «какой город» — запрещены.` : "",
  ]
    .filter(Boolean)
    .join("\n");
  const body = scripts
    .filter((s) => s.id !== "funnel" && !skip.has(s.step))
    .map((s) => `### ${s.title}\n${s.body.trim()}`)
    .join("\n\n");
  return `

СКРИПТЫ СТУДИИ:
${season}

${live}

${body}
`;
}
