import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { describe, it } from "node:test";
import { journalPeriods, journalChunks, nextPeriod, periodOfDate, spanOf, expandPeriodKeys, chunkDone, groupAge, chunkOverlapsLife, lifeLabel, pulledPeriodKeys } from "./crm-journal-periods.ts";

describe("ручной журнал с Alfa", () => {
  it("кварталы с конца, полугодие и год — пачки", () => {
    const p = journalPeriods(new Date("2026-09-09T12:00:00Z"), 2);
    assert.equal(p[0].key, "2026q4");
    assert.equal(p[1].key, "2026q3");
    assert.equal(p.length, 9);
    assert.equal(nextPeriod(["2026q4"], p)?.key, "2026q3");
    assert.equal(periodOfDate(new Date(2024, 2, 5)), "2024q1");
    assert.equal(spanOf([{ date: "01.09.2025" }, { date: "10.03.2026" }]).from, "сен 2025");
    assert.deepEqual(expandPeriodKeys(["2024-1", "2024-2"]).sort(), ["2024q1", "2024q2", "2024q3", "2024q4"]);
    const year = journalChunks("year", new Date("2026-09-09T12:00:00Z"), 1);
    assert.equal(year[0].key, "2026");
    assert.equal(year[0].keys.length, 4);
    assert.equal(chunkDone(year[0], year[0].keys), true);
    const half = journalChunks("half", new Date("2026-09-09T12:00:00Z"), 1);
    assert.equal(half[0].key, "2026h2");
    assert.match(half[0].label, /июл–дек 2026/);
    assert.equal(groupAge("01.02.2026", "30.06.2026", new Date("2026-09-09")).id, "young");
    assert.equal(groupAge("01.09.2022", "30.06.2026", new Date("2026-09-09")).id, "old");
    assert.equal(chunkOverlapsLife({ from: "01.01.2024", to: "31.03.2024" }, "01.02.2026", "30.06.2026"), false);
    assert.equal(chunkOverlapsLife({ from: "01.04.2026", to: "30.06.2026" }, "01.02.2026", "30.06.2026"), true);
    assert.match(lifeLabel("01.02.2026", "30.06.2026"), /фев 2026/);
    assert.deepEqual(pulledPeriodKeys({ done: ["2024q1", "2024q2", "2024q3", "2024q4"] }), []);
    assert.deepEqual(pulledPeriodKeys({ done: ["2026q3"] }), ["2026q3"]);
    assert.deepEqual(pulledPeriodKeys({ pulled: { "2026q1": "x" }, done: ["2026q1", "2026q2"] }).sort(), ["2026q1"]);
  });

  it("только кнопка группы и порция, фон сам не качает", () => {
    const pull = readFileSync(new URL("./crm-journal-pull.ts", import.meta.url), "utf8");
    assert.match(pull, /kind === "life"/);
    assert.match(pull, /journalLife/);
    assert.match(pull, /lastLife/);
    assert.match(pull, /Определено/);
    assert.match(pull, /recheck/);
    assert.match(pull, /пакет оборвался|дозаписали/);
    assert.match(pull, /journalFill: \{ done:/);
    assert.doesNotMatch(pull, /inferredPeriodKeys\(card\?\.calendar/);
    const inbound = readFileSync(new URL("./crm-journal-inbound.ts", import.meta.url), "utf8");
    assert.match(inbound, /hitCap/);
    assert.match(inbound, /opts\?\.lite \|\| windowed/);
    assert.match(inbound, /date_from: ymd\(date_from\)/);
    assert.match(inbound, /date_to: ymd\(date_to\)/);
    const ui = readFileSync(new URL("../components/admin-crm-settings.tsx", import.meta.url), "utf8");
    assert.match(pull, /probeGroupLife/);
    assert.match(pull, /kind === "details"/);
    assert.match(pull, /clampGrain/);
    assert.match(ui, /Перепроверить школу|Перепроверить все группы/);
    assert.match(ui, /Найти группу/);
    assert.match(ui, /ещё нет/);
    assert.match(ui, /домашнее задание/);
    assert.match(ui, /таблица учеников/);
    assert.match(ui, /тема, ДЗ, комментарий/);
    assert.match(ui, /Стоп/);
    assert.match(inbound, /probeGroupLife/);
    assert.match(ui, /Определить сроки групп/);
    assert.match(ui, /lastLife/);
    assert.match(ui, /Определено/);
    assert.match(ui, /ageLabel/);
    assert.match(ui, /молодая/);
    assert.match(ui, /GroupFillList/);
    assert.match(ui, /I квартал|Квартал/);
    assert.match(ui, /Порция за одно нажатие/);
    assert.match(ui, /сверено/);
    assert.match(ui, /пропусков не обнаружено|дубликатов нет/);
    assert.match(ui, /HIST_TABS/);
    assert.match(ui, /Календарь ученика/);
    assert.match(ui, /Деньги на карточке/);
    assert.match(ui, /На странице/);
    assert.match(ui, /toggleOpen/);
    assert.doesNotMatch(ui, /max-h-\[36rem\]/);
    assert.doesNotMatch(ui, /if \(open && aid === open\) return -1/);
    assert.match(ui, /История из Alfa/);
    assert.match(ui, /crm-settings-tab/);
    assert.match(ui, /w-fit shrink-0/);
    assert.doesNotMatch(ui, /BTN_LOAD_SM, "min-w-0 flex-1"/);
    assert.match(ui, /ra-progress-run/);
    assert.match(ui, /bg-primary/);
    assert.match(ui, /overflow-anchor:none/);
    assert.match(ui, /Шаг 2 · тема, ДЗ, комментарий, таблица учеников/);
    assert.match(ui, /Загрузить явки/);
    assert.match(ui, /Загрузить тему, ДЗ, комментарий и таблицу учеников всех кварталов/);
    assert.match(ui, /грузить нечего/);
    assert.match(ui, /перепроверен/);
    assert.match(pull, /rechecked/);
    assert.match(ui, /periodKey: part.key/);
    assert.doesNotMatch(ui, /setInterval\(\(\) => \{\s*if \(document.hidden/);
    const pack = readFileSync(new URL("./crm-packet-queue.ts", import.meta.url), "utf8");
    assert.doesNotMatch(pack, /inboundJournalChunk\(polJ.journalNext/);
    const api = readFileSync(new URL("./admin-schedule.ts", import.meta.url), "utf8");
    assert.match(api, /periodKey/);
  });
});
